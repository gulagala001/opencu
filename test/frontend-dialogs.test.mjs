import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {join} from 'node:path';
import {build} from 'esbuild';
import {frontendComponents} from './fixtures/frontend-components.mjs';

test('window sharing, annotation and image preview preserve draft-only actions and modal focus on touch layout', async t => {
  const {page, errors, output} = await frontendComponents(t, {width: 390, height: 820}, {hasTouch: true});
  const {outputFiles} = await build({bundle: true, write: false, format: 'iife', platform: 'browser', loader: {'.css': 'text'}, define: {'process.env.NODE_ENV': '"production"'}, stdin: {resolveDir: process.cwd(), loader: 'jsx', contents: `
    import React,{useState}from'react';import{createRoot}from'react-dom/client';import{WindowShare}from'./src/client/window-share.jsx';import{PageAnnotation}from'./src/client/page-annotation.jsx';import{ImageDialog}from'./src/client/tool-image.jsx';
    const image='data:image/svg+xml;base64,'+btoa('<svg xmlns="http://www.w3.org/2000/svg" width="640" height="360"><rect width="640" height="360" fill="#e8effb"/><rect x="80" y="70" width="400" height="160" rx="12" fill="#3877e8"/><text x="110" y="160" fill="white" font-size="32">Owned preview fixture</text></svg>');
    const frame={at:Date.now(),id:'frozen-frame',tabId:'A',actor:'synthetic-actor',controlEpoch:4,width:640,height:360,mediaType:'image/svg+xml',data:image.split(',')[1]};
    window.fixture={drafts:[],added:[],calls:[]};
    const conversation={createDrafts:(_id,files)=>{window.fixture.drafts.push(...files);return files.map((file,i)=>({id:'draft-'+(window.fixture.drafts.length+i)}));},releaseDraftAttachments:()=>{}};
    const inputActions={addAttachments:ids=>{window.fixture.added.push(...ids);return true;}};
    window.fetch=async path=>new Response(JSON.stringify(String(path).includes('share-windows')?{windows:[{pid:1,window_id:2,app_name:'Fixture App',title:'Owned window',active:true}]}:{name:'Owned window',screenshot:frame.data,mediaType:frame.mediaType,text:'Owned window text'}));
    const api=async(op,id,input)=>{window.fixture.calls.push({op,id,input});return{frame,elements:[]};};
    function Harness(){const[open,setOpen]=useState(false);return <div className="tx-cu-pane"><div className="tx-cu-chip"><WindowShare sessionId="fixture" conversation={conversation} inputActions={inputActions}/></div><PageAnnotation sessionId="fixture" target={{id:'A',browserId:'browser'}} frame={frame} api={api} conversation={conversation} inputActions={inputActions}/><button id="image" type="button" onClick={()=>setOpen(true)}>查看交付截图</button>{open&&<ImageDialog src={image} onClose={()=>setOpen(false)}/>}</div>;}
    createRoot(document.getElementById('root')).render(<Harness/>);
  `}});
  await page.setContent('<style>:root{color-scheme:light dark}body{margin:0;background:Canvas;color:CanvasText}.tx-cu-pane{box-sizing:border-box;width:100%;height:820px}</style><div id="root"></div>');
  await page.addStyleTag({content: await readFile(new URL('../src/client/computer-use.css', import.meta.url), 'utf8')});
  await page.addScriptTag({content: outputFiles[0].text});
  const share = page.getByRole('button', {name: '分享窗口', exact: true});
  await share.tap();
  const shareDialog = page.getByRole('dialog', {name: '分享窗口', exact: true});
  await shareDialog.getByLabel('搜索应用或窗口').fill('Fixture');
  await shareDialog.getByRole('button', {name: /Fixture App/}).tap();
  await shareDialog.waitFor({state: 'hidden'});
  assert.deepEqual(await page.evaluate(() => window.fixture.drafts.map(file => file.name)), ['Owned window.png', 'Owned window-窗口文字.txt']);
  assert.equal(await share.evaluate(node => node === document.activeElement), true);
  const annotate = page.getByRole('button', {name: '批注页面', exact: true});
  await annotate.tap();
  const annotation = page.getByRole('dialog', {name: '批注页面', exact: true});
  await annotation.getByRole('img', {name: '待批注的冻结页面'}).waitFor();
  await page.waitForFunction(() => document.querySelector('.tx-cu-annotation-surface img')?.naturalWidth > 0);
  const box = await annotation.locator('.tx-cu-annotation-surface').boundingBox();
  await page.mouse.move(box.x + box.width * .2, box.y + box.height * .2);
  await page.mouse.down(); await page.mouse.move(box.x + box.width * .6, box.y + box.height * .7, {steps: 5}); await page.mouse.up();
  await annotation.getByLabel('批注说明').fill('请调整这个区域');
  assert.equal(await annotation.evaluate(node => node.scrollWidth > node.clientWidth), false);
  if (output) await page.screenshot({path: join(output, 'annotation-touch-light.png')});
  await annotation.getByRole('button', {name: '加入输入框', exact: true}).tap();
  await annotation.waitFor({state: 'hidden'});
  const drafts = await page.evaluate(async () => Promise.all(window.fixture.drafts.slice(2).map(async file => ({name: file.name, type: file.type, size: file.size, text: file.type === 'text/plain' ? await file.text() : null}))));
  assert.deepEqual(drafts.map(file => file.name), ['网页批注.png', '网页批注.txt']);
  assert.ok(drafts[0].size > 100); assert.ok(drafts[1].text.includes('请调整这个区域'));
  assert.equal(await annotate.evaluate(node => node === document.activeElement), true);
  assert.equal(await page.evaluate(() => window.fixture.calls[0].input.tabId), 'A');
  await page.locator('#image').tap();
  const image = page.getByRole('dialog', {name: '截图预览', exact: true});
  await image.getByRole('img').waitFor();
  await image.getByRole('button', {name: '放大截图', exact: true}).tap();
  await page.emulateMedia({colorScheme: 'dark', reducedMotion: 'reduce'});
  if (output) await page.screenshot({path: join(output, 'image-touch-dark.png')});
  await image.getByRole('button', {name: '关闭截图预览', exact: true}).press('Escape');
  await image.waitFor({state: 'hidden'});
  assert.equal(await page.locator('#image').evaluate(node => node === document.activeElement), true);
  assert.deepEqual(errors, []);
});
