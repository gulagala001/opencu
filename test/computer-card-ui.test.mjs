import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { join } from 'node:path';
import { build } from 'esbuild';
import { frontendComponents } from './fixtures/frontend-components.mjs';

test('CU activity expands one plain result body with natural screenshots, file rows and visible failures', async t => {
  const {page, errors, output} = await frontendComponents(t, {width: 390, height: 820});
  const {outputFiles} = await build({bundle:true,write:false,platform:'browser',format:'iife',define:{'process.env.NODE_ENV':'"production"'},stdin:{resolveDir:process.cwd(),loader:'jsx',contents:`
    import React from 'react';import{createRoot}from'react-dom/client';import{ComputerCard}from'./src/client/computer-card.jsx';
    const image=(width,height)=>'data:image/svg+xml,'+encodeURIComponent('<svg xmlns="http://www.w3.org/2000/svg" width="'+width+'" height="'+height+'"><rect width="'+width+'" height="'+height+'" fill="#3977e8"/></svg>');
    const loadImage=async attachment=>{window.fixture.loaded.push(attachment.id);return attachment.id==='wide'?image(480,120):image(120,480);};
    const block={kind:'tool-result',call:{argsRaw:JSON.stringify({title:'  查看  网页  ',code:'await tab.getScreenshot()'})},content:[{type:'image',attachment:{id:'wide'}},{type:'image',attachment:{id:'tall'}},{type:'text',text:'AX output'}],meta:{computerUseTarget:{kind:'tab',label:'示例页面',origin:'https://example.com'},computerUseFiles:[{name:'交付结果.txt',path:'/owned/deliver.txt',bytes:2048},{name:'另一个文件.txt',path:'/owned/other.txt',bytes:512}],computerUseError:null}};
    const failed={kind:'tool-result',call:{argsRaw:'null'},content:[{type:'text',text:'Execution failed: 失败细节'}],meta:{computerUseError:'失败细节'}};
    window.fixture={opened:[],loaded:[]};createRoot(document.getElementById('root')).render(<><div id="success"><ComputerCard block={block} toolName="computer_use" sessionId="test" callId="call" loadImage={loadImage} openFile={path=>window.fixture.opened.push(path)}/></div><div id="failure"><ComputerCard block={failed} toolName="computer_use" sessionId="test" callId="failed"/></div></>);
  `}});
  await page.addStyleTag({content:await readFile(new URL('../src/client/computer-use.css',import.meta.url),'utf8')});
  await page.addScriptTag({content:outputFiles[0].text});
  const card=page.locator('#success .tx-cu-card'),row=card.locator('.tx-cu-card-heading');
  assert.equal(await row.getAttribute('aria-expanded'),'false');
  await page.getByText('示例页面',{exact:true}).waitFor();
  assert.equal(await card.locator('.tx-cu-card-body').count(),0);
  assert.equal(await card.locator('.tx-cu-card-image,.tx-cu-export-files').count(),0,'folded activity has no media or file tiles');
  assert.equal(await page.getByLabel('操作代码').count(),0);
  assert.deepEqual(await page.evaluate(()=>window.fixture.loaded),[],'folded results do not load screenshots');
  await page.locator('#failure .tx-cu-card-failure').getByText('失败细节',{exact:true}).waitFor();
  assert.equal(await page.locator('#failure .tx-cu-card-heading').getAttribute('aria-expanded'),'false','null args remain safe while the failure stays visible');
  await row.click();
  assert.equal(await row.getAttribute('aria-expanded'),'true');
  assert.equal(await card.locator('.tx-cu-card-body').getAttribute('id'),await row.getAttribute('aria-controls'));
  assert.equal(await card.locator('details,summary').count(),0,'one disclosure exposes all results without a second details layer');
  await page.getByLabel('操作代码').waitFor();await page.getByLabel('操作输出').waitFor();
  const images=card.locator('.tx-cu-card-image'),image=images.first();await image.waitFor();
  await page.waitForFunction(()=>[...document.querySelectorAll('#success .tx-cu-card-image')].every(image=>image.naturalWidth>0));
  const size=await image.boundingBox(),tall=await images.nth(1).boundingBox();
  assert.ok(size.width>192&&size.width/size.height>3.9,'wide screenshots use available width rather than a 192-pixel tile');
  assert.ok(tall.height<=192&&Math.abs(tall.width/tall.height-.25)<.01,'portrait screenshots preserve their ratio and 192-pixel height limit');
  assert.ok(tall.y>=size.y+size.height,'screenshots flow in one column');
  const fileRows=card.locator('.tx-cu-export-files button'),firstFile=await fileRows.first().boundingBox(),secondFile=await fileRows.nth(1).boundingBox();
  assert.ok(secondFile.y>=firstFile.y+firstFile.height,'file delivery is a single list of rows');
  assert.equal(await fileRows.first().evaluate(node=>getComputedStyle(node).borderTopWidth),'0px');
  await page.getByRole('button',{name:/交付结果.txt/}).click();
  assert.deepEqual(await page.evaluate(()=>window.fixture.opened),['/owned/deliver.txt']);
  await card.getByRole('button',{name:'查看截图大图',exact:true}).first().click();
  await page.getByRole('dialog',{name:'截图预览'}).waitFor();
  await page.getByRole('dialog',{name:'截图预览'}).press('Escape');
  assert.equal(await card.getByRole('button',{name:'查看截图大图',exact:true}).first().evaluate(node=>node===document.activeElement),true,'closing the viewer returns focus to its image');
  assert.equal(await card.evaluate(node=>node.scrollWidth>node.clientWidth),false);
  if(output)await page.screenshot({path:join(output,'card-light.png')});
  await page.emulateMedia({colorScheme:'dark',reducedMotion:'reduce'});
  if(output)await page.screenshot({path:join(output,'card-dark.png')});
  await card.evaluate(node=>node.style.width='180px');
  assert.equal(await card.evaluate(node=>node.scrollWidth>node.clientWidth),false,'narrow cards keep result rows within their available width');
  await row.click();assert.equal(await card.locator('.tx-cu-card-body').count(),0,'folding the activity removes the whole result body');
  assert.equal(await page.locator('#failure .tx-cu-card-failure').isVisible(),true);
  assert.deepEqual(errors,[]);
});
