import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {join} from 'node:path';
import {build} from 'esbuild';
import {frontendComponents} from './fixtures/frontend-components.mjs';

test('annotation editor compares frozen images, sends supported styles and preserves draft admission on touch layouts', async t => {
  const {page, errors, output} = await frontendComponents(t, {width: 1100, height: 820}, {hasTouch: true});
  const {outputFiles} = await build({bundle: true, write: false, platform: 'browser', format: 'iife', loader: {'.css': 'text'}, define: {'process.env.NODE_ENV': '"production"'}, stdin: {resolveDir: process.cwd(), loader: 'jsx', contents: `
    import React from 'react';import{createRoot}from'react-dom/client';import{PageAnnotation}from'./src/client/page-annotation.jsx';
    const canvas=document.createElement('canvas');canvas.width=800;canvas.height=500;
    const paint=color=>{const c=canvas.getContext('2d');c.fillStyle=color;c.fillRect(0,0,800,500);return canvas.toDataURL('image/png').split(',')[1];};
    const original=paint('#edf2f7'),preview=paint('#c7dfea');
    const frame={id:'frozen-1',tabId:'tab-1',actor:'viewer-1',controlEpoch:7,width:800,height:500,mediaType:'image/png',data:original,url:'https://fixture.invalid/page',at:1700000000000};
    const element={key:'element-1',tag:'div',id:'card',label:'示例卡片',region:{x:.2,y:.2,width:.6,height:.6},styles:{width:'180px',height:'120px','font-weight':'400','font-family':'sans-serif','background-color':'rgb(237, 242, 247)'},ancestry:['main','section']};
    window.fixture={calls:[],files:[],releases:0,admit:false,previewCount:0};
    const api=async(op,id,input)=>{window.fixture.calls.push({op,id,input});if(op==='annotation')return{frame,elements:[element]};if(op==='annotation-style'){window.fixture.previewCount++;return{frame:{...frame,id:'preview-'+window.fixture.previewCount,data:preview,at:frame.at+1000},element:{...element,styles:{...element.styles,...input.changes}},changes:input.changes,restored:{restored:true,conflicts:[]},controlEpoch:7+window.fixture.previewCount};}throw Error('Unexpected operation '+op);};
    const conversation={createDrafts(id,files){window.fixture.files=files;return files.map((file,i)=>({id:'draft-'+i,file}));},releaseDraftAttachments(){window.fixture.releases++;}};
    const inputActions={addAttachments(ids){window.fixture.attachments=ids;return window.fixture.admit;}};
    createRoot(document.getElementById('root')).render(<PageAnnotation sessionId="session-1" target={{id:'tab-1',browserId:'browser'}} frame={frame} api={api} conversation={conversation} inputActions={inputActions}/>);
  `}});
  await page.addStyleTag({content: await readFile(new URL('../src/client/computer-use.css', import.meta.url), 'utf8')});
  await page.addScriptTag({content: outputFiles[0].text});
  const opener = page.getByRole('button', {name: '批注页面', exact: true});
  await opener.tap();
  const editor = page.getByRole('dialog', {name: '批注页面', exact: true});
  const image = editor.getByAltText('待批注的冻结页面');
  await image.evaluate(img => img.decode());
  await editor.getByText('正在读取页面元素…', {exact: true}).waitFor({state: 'hidden'});
  await editor.getByRole('button', {name: '选择元素', exact: true}).tap();
  const surface = await editor.locator('.tx-cu-annotation-surface').boundingBox();
  await page.touchscreen.tap(surface.x + surface.width / 2, surface.y + surface.height / 2);
  await editor.locator('.tx-cu-annotation-element strong').getByText('div#card', {exact: true}).waitFor();
  await editor.getByText('调整样式', {exact: true}).click();
  assert.equal(await editor.locator('.tx-cu-style-fields input').count(), 20, 'only the twenty supported properties are available');
  await editor.getByLabel('预览宽度', {exact: true}).fill('240px');
  await editor.getByLabel('预览背景颜色', {exact: true}).fill('rgb(25, 120, 180)');
  await editor.getByLabel('预览字体', {exact: true}).fill('Inter, sans-serif');
  await editor.getByText('间距', {exact: true}).click();
  await editor.getByLabel('预览右外距', {exact: true}).fill('28px');
  await editor.getByText('圆角', {exact: true}).click();
  await editor.getByLabel('预览左下圆角', {exact: true}).fill('12px');
  await editor.getByText('5 项调整', {exact: true}).waitFor();
  await editor.getByRole('button', {name: '预览样式', exact: true}).tap();
  await editor.getByText(/临时样式已恢复，当前显示预览图/).waitFor();
  await image.evaluate(img => img.decode());
  assert.deepEqual(await page.evaluate(() => window.fixture.calls.at(-1).input), {
    actor: 'viewer-1', tabId: 'tab-1', controlEpoch: 7, sourceFrameId: 'frozen-1', elementKey: 'element-1',
    changes: {width: '240px', 'background-color': 'rgb(25, 120, 180)', 'font-family': 'Inter, sans-serif', 'margin-right': '28px', 'border-bottom-left-radius': '12px'},
  });
  const previewSource = await image.getAttribute('src');
  await editor.getByRole('button', {name: '显示原图', exact: true}).tap();
  await image.evaluate(img => img.decode());
  assert.notEqual(await image.getAttribute('src'), previewSource);
  assert.equal(await editor.locator('.tx-cu-annotation-viewport').getAttribute('data-view'), 'original');
  await editor.getByRole('button', {name: '显示预览图', exact: true}).tap();
  await image.evaluate(img => img.decode());
  assert.equal(await image.getAttribute('src'), previewSource);
  assert.equal(await page.evaluate(() => window.fixture.previewCount), 1, 'comparison switches retained images without another page operation');
  if (output) await page.screenshot({path: join(output, 'editor-desktop.png')});
  await editor.getByRole('button', {name: '重置右外距', exact: true}).click();
  assert.equal(await editor.getByLabel('预览右外距', {exact: true}).inputValue(), '');
  assert.equal(await editor.locator('.tx-cu-annotation-viewport').getAttribute('data-view'), 'original');
  await editor.getByRole('button', {name: '重置全部', exact: true}).click();
  assert.equal(await editor.getByRole('button', {name: '预览样式', exact: true}).isDisabled(), true);
  assert.equal(await editor.getByRole('button', {name: '显示预览图', exact: true}).count(), 0);
  await editor.getByLabel('预览宽度', {exact: true}).fill('180px');
  assert.equal(await editor.getByRole('button', {name: '预览样式', exact: true}).isDisabled(), true, 'unchanged computed values do not count as adjustments');
  await editor.getByLabel('预览宽度', {exact: true}).fill('240px');
  await editor.getByLabel('预览字重', {exact: true}).fill('600');
  await editor.getByRole('button', {name: '预览样式', exact: true}).tap();
  await image.evaluate(img => img.decode());
  await editor.getByLabel('批注说明', {exact: true}).fill('增加留白，保留原有内容');
  await page.setViewportSize({width: 390, height: 800});
  const bounds = await editor.boundingBox(), action = editor.getByRole('button', {name: '加入输入框', exact: true});
  const actionBounds = await action.boundingBox();
  assert.equal(await editor.evaluate(node => node.scrollWidth <= node.clientWidth), true, 'touch editor has no horizontal overflow');
  assert.ok(actionBounds.y + actionBounds.height <= bounds.y + bounds.height, 'draft action remains visible below the scrollable inspector');
  if (output) await page.screenshot({path: join(output, 'editor-touch.png')});
  await action.tap();
  await editor.getByRole('alert').filter({hasText: '输入区正在发送'}).waitFor();
  assert.equal(await page.evaluate(() => window.fixture.releases), 1, 'failed admission releases the new draft attachments');
  assert.equal(await editor.isVisible(), true);
  await page.evaluate(() => {window.fixture.admit = true;});
  await action.tap();
  await editor.waitFor({state: 'hidden'});
  const text = await page.evaluate(() => window.fixture.files.find(file => file.name.endsWith('.txt')).text());
  const metadata = JSON.parse(text.slice(text.indexOf('{'), text.lastIndexOf('}') + 1));
  assert.equal(metadata.comment, '增加留白，保留原有内容');
  assert.equal(metadata.element.styles.width, '180px');
  assert.deepEqual(metadata.stylePreview.changes, {width: '240px', 'font-weight': '600'});
  assert.equal(metadata.stylePreview.restored.restored, true);
  assert.deepEqual(await page.evaluate(() => window.fixture.attachments), ['draft-0', 'draft-1']);
  assert.equal(await opener.evaluate(node => node === document.activeElement), true);
  assert.deepEqual(await page.evaluate(() => window.fixture.calls.map(call => call.op)), ['annotation', 'annotation-style', 'annotation-style']);
  assert.deepEqual(errors, []);
});
